"""Writes the T-60 fixtures to `apps/api/tests/fixtures/lab_ocr/`.

    apps/api/.venv/bin/python eval/lab_ocr/make_fixtures.py

These are STAND-INS made by this script, not Đạt's package (T-20, T-34). When that package
arrives, copy its files over these and keep its `ground_truth.json`; the tests and the runner
read the same file names. Every file is synthetic and carries the synthetic banner.
"""

from __future__ import annotations

import hashlib
import io
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

import variants  # noqa: E402
from lab_reports import LAYOUT_ID, Report, render_pdf, truth, with_changes  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT = REPO_ROOT / "apps" / "api" / "tests" / "fixtures" / "lab_ocr"
SEED = 60

LAB_A = Report(report_id="SYN-LAB-A-001")
LAB_B = Report(
    report_id="SYN-LAB-B-001",
    collection_date="2026-09-18",
    values={
        "volume": "2.5",
        "ph": "7.4",
        "concentration": "22.5",
        "total_count": "56",
        "progressive_motility": "41",
        "non_progressive_motility": "12",
        "immotile": "47",
        "normal_forms": "6",
    },
)
LAB_C = with_changes(
    Report(report_id="SYN-LAB-C-001", collection_date="05/10/26"),
    values={**Report().values, "volume": "2,5", "ph": "7,4"},
    units={"concentration": "", "normal_forms": ""},
)


def _expected(report: Report, overrides: dict[str, dict[str, Any]]) -> dict[str, Any]:
    fields = {
        field_id: {**item, "status": "UNCONFIRMED", "flags": []}
        for field_id, item in truth(report)["fields"].items()
    }
    for field_id, change in overrides.items():
        fields[field_id].update(change)
    return fields


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    lab_b_pdf = variants.make(render_pdf(LAB_B), "scanned", SEED)
    page = variants.render(lab_b_pdf, 200)[0].convert("L")
    png = io.BytesIO()
    page.save(png, format="PNG", optimize=True)

    files = {
        "lab_A_clean_textlayer.pdf": render_pdf(LAB_A),
        "lab_B_scanned.pdf": lab_b_pdf,
        "lab_B_scanned.png": png.getvalue(),
        "lab_C_ambiguous_textlayer.pdf": render_pdf(LAB_C),
    }
    for name, data in files.items():
        (OUT / name).write_bytes(data)

    unclear = {"status": "NEEDS_CONFIRMATION", "flags": ["DECIMAL_SEPARATOR_UNCLEAR"]}
    no_unit = {"unit": None, "status": "NEEDS_CONFIRMATION", "flags": ["UNIT_MISSING"]}
    lab_b = _expected(LAB_B, {})
    ground_truth = {
        "label_source": "SOFTWARE_ORACLE",
        "clinical_truth": "NOT_EVALUATED",
        "provenance": "STAND_IN generated by eval/lab_ocr/make_fixtures.py; replace with the "
        "T-20/T-34 package when it is available",
        "layout_id": LAYOUT_ID,
        "files": {
            "lab_A_clean_textlayer.pdf": {
                "purpose": "Clean reference: text layer, all units present",
                "method": "TEXT_LAYER",
                "fields": _expected(LAB_A, {}),
            },
            "lab_B_scanned.pdf": {
                "purpose": "Real OCR path: turned 2.5 degrees, noisy, soft, no text layer",
                "method": "OCR",
                "fields": lab_b,
            },
            "lab_B_scanned.png": {
                "purpose": "Real OCR path, as a picture",
                "method": "OCR",
                "fields": lab_b,
            },
            "lab_C_ambiguous_textlayer.pdf": {
                "purpose": "Flag coverage: decimal commas, missing units, dd/mm/yy date",
                "method": "TEXT_LAYER",
                "fields": _expected(
                    LAB_C,
                    {
                        "volume": unclear,
                        "ph": unclear,
                        "concentration": no_unit,
                        "normal_forms": no_unit,
                        "collection_date": {
                            "value": None,
                            "status": "NEEDS_CONFIRMATION",
                            "flags": ["DATE_FORMAT_AMBIGUOUS"],
                        },
                    },
                ),
            },
        },
        "sha256": {name: hashlib.sha256(data).hexdigest() for name, data in files.items()},
    }
    (OUT / "ground_truth.json").write_text(
        json.dumps(ground_truth, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    for name, data in files.items():
        print(f"{name}: {len(data)} bytes")


if __name__ == "__main__":
    main()
